// ─── Filter helpers ───────────────────────────────────────────

export function getDoctorById(id: string): Doctor | undefined {
  return MOCK_DOCTORS.find((d) => d.id === id);
}

export function getDoctorsBySpecialization(spec: string): Doctor[] {
  return MOCK_DOCTORS.filter((d) => d.specialization === spec);
}

export function getAvailableDoctors(): Doctor[] {
  return MOCK_DOCTORS.filter((d) => d.isAvailable && d.isVerified);
}

export function searchDoctors(query: string): Doctor[] {
  const q = query.toLowerCase();
  return MOCK_DOCTORS.filter(
    (d) =>
      d.firstName.toLowerCase().includes(q) ||
      d.lastName.toLowerCase().includes(q) ||
      d.specialization.toLowerCase().includes(q) ||
      d.hospital?.toLowerCase().includes(q)
  );
}
